#!/usr/bin/env python3
"""TensorRT audit, part 1: can the ScienceQA / TextVQA gap be explained by output handling?

Compares C2 (llama.cpp Q8_0), C3 (llama.cpp Q4_K_M), T16, T8, T4 (TensorRT FP16 / INT8 SQ / INT4 AWQ)
record by record on the committed results. Checks:
  1. output format: raw replies that are not a bare answer, parser disagreements (v1 vs v2),
     unparsed / out-of-range answers, finish_reason other than "stop", output token counts
  2. prediction agreement between configs (identical predicted answer)
  3. answer-position bias: share of predictions per letter vs the ground truth
  4. where the gap is: accuracy by prompt length (characters of context + question + choices)

Usage: python3 tensorrt/audit_outputs.py [--out tensorrt/audit/outputs.md]
"""
import argparse
import collections
import json
import re
from pathlib import Path

CFG = {
    "C2": "results/config2_F16v_Q8l__{ds}.jsonl",
    "C3": "results/config3_F16v_Q4l__{ds}.jsonl",
    "T16": "results_trt/configT16_TRT_F16v_F16l__{ds}.jsonl",
    "T8": "results_trt/configT8_TRT_F16v_INT8l__{ds}.jsonl",
    "T4": "results_trt/configT4_TRT_F16v_INT4l__{ds}.jsonl",
}
PAIRS = [("C2", "T16"), ("C2", "C3"), ("T16", "T8"), ("T16", "T4"), ("C2", "T8"), ("C3", "T4"), ("T8", "T4")]


def load(ds):
    out = {}
    for k, pat in CFG.items():
        p = Path(pat.format(ds=ds))
        rows = {}
        for line in open(p):
            if line.strip():
                r = json.loads(line)
                rows[r["idx"]] = r
        out[k] = rows
    return out


def val(r):
    s = r.get("score")
    return float(s) if s is not None else float(bool(r.get("correct")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    L = ["# TensorRT audit, part 1: output handling (ScienceQA, TextVQA)", "",
         "Generated by `tensorrt/audit_outputs.py` from the committed per-record results. "
         "Records with a request error in any config are left out, so every config is scored on the same records.", ""]

    # ---------------------------------------------------------------- ScienceQA
    d = load("scienceqa")
    ids = sorted(set.intersection(*[{i for i, r in rows.items() if not r.get("error")} for rows in d.values()]))
    L += ["## ScienceQA", "", f"{len(ids)} records valid in all five configs.", "",
          "### 1. Output format", "",
          "| config | accuracy | bare single letter | other raw reply | parser v1 != v2 | unparsed | finish != stop | output tokens (max) |",
          "|---|---:|---:|---:|---:|---:|---:|---|"]
    examples = {}
    for k, rows in d.items():
        rs = [rows[i] for i in ids]
        bare = sum(bool(re.fullmatch(r"\s*\(?[A-Z]\)?\.?\s*", str(r.get("prediction_raw") or ""))) for r in rs)
        other = [r for r in rs if not re.fullmatch(r"\s*\(?[A-Z]\)?\.?\s*", str(r.get("prediction_raw") or ""))]
        examples[k] = [str(r.get("prediction_raw"))[:60] for r in other[:5]]
        dis = sum(r.get("pred_parser_v1") != r.get("pred_parser_v2") for r in rs)
        unp = sum(r.get("predicted") in (None, "") or (ord(str(r["predicted"])[0]) - 65 >= len(r["choices"])) for r in rs)
        fin = collections.Counter(r.get("finish_reason") for r in rs)
        ntok = [r.get("n_output_tokens") for r in rs if r.get("n_output_tokens") is not None]
        acc = 100 * sum(val(r) for r in rs) / len(rs)
        L.append(f"| {k} | {acc:.2f} | {bare} | {len(other)} | {dis} | {unp} | {sum(v for f, v in fin.items() if f != 'stop')} | "
                 f"{(str(collections.Counter(ntok).most_common(3)) + ' max ' + str(max(ntok))) if ntok else 'n/a (llama.cpp)'} |")
    L += ["", "Examples of non-bare replies: " + "; ".join(f"{k}: {v}" for k, v in examples.items() if v), ""]

    L += ["### 2. Identical predictions", "",
          "| pair | identical | both right | only first right | only second right |", "|---|---:|---:|---:|---:|"]
    for a, b in PAIRS:
        same = sum(d[a][i]["predicted"] == d[b][i]["predicted"] for i in ids)
        br = sum(val(d[a][i]) == 1 and val(d[b][i]) == 1 for i in ids)
        oa = sum(val(d[a][i]) == 1 and val(d[b][i]) == 0 for i in ids)
        ob = sum(val(d[a][i]) == 0 and val(d[b][i]) == 1 for i in ids)
        L.append(f"| {a} vs {b} | {same} ({100 * same / len(ids):.1f}%) | {br} | {oa} | {ob} |")

    L += ["", "### 3. Answer-position bias (share of predictions per letter, %)", "",
          "| config | A | B | C | D | E |", "|---|---:|---:|---:|---:|---:|"]
    gt = collections.Counter(d["C2"][i]["gt_answer"] for i in ids)
    L.append("| ground truth | " + " | ".join(f"{100 * gt[c] / len(ids):.1f}" for c in "ABCDE") + " |")
    for k, rows in d.items():
        c = collections.Counter(rows[i]["predicted"] for i in ids)
        L.append(f"| {k} | " + " | ".join(f"{100 * c[x] / len(ids):.1f}" for x in "ABCDE") + " |")
    # Errors made by T8/T4 where T16 was right: which letter did they pick?
    for k in ("T8", "T4"):
        lost = [i for i in ids if val(d["T16"][i]) == 1 and val(d[k][i]) == 0]
        c = collections.Counter(d[k][i]["predicted"] for i in lost)
        L.append(f"\n{k} on the {len(lost)} records T16 gets right and {k} gets wrong picks: "
                 + ", ".join(f"{x} {c[x]}" for x in "ABCDE" if c[x]))

    L += ["", "### 4. Accuracy by prompt length (characters of context + question + choices)", "",
          "| length | n | C2 | C3 | T16 | T8 | T4 | T16 - T8 | T16 - T4 |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    length = {i: len(d["C2"][i].get("context") or "") + len(d["C2"][i]["question"]) + sum(len(c) for c in d["C2"][i]["choices"])
              for i in ids}
    qs = sorted(length.values())
    edges = [qs[len(qs) * q // 4] for q in (1, 2, 3)]
    def bucket(n):
        return 0 if n < edges[0] else 1 if n < edges[1] else 2 if n < edges[2] else 3
    names = [f"< {edges[0]}", f"{edges[0]}-{edges[1] - 1}", f"{edges[1]}-{edges[2] - 1}", f">= {edges[2]}"]
    for bi, name in enumerate(names):
        bi_ids = [i for i in ids if bucket(length[i]) == bi]
        acc = {k: 100 * sum(val(d[k][i]) for i in bi_ids) / len(bi_ids) for k in CFG}
        L.append(f"| {name} | {len(bi_ids)} | " + " | ".join(f"{acc[k]:.1f}" for k in CFG)
                 + f" | {acc['T16'] - acc['T8']:+.1f} | {acc['T16'] - acc['T4']:+.1f} |")
    has_ctx = [i for i in ids if (d["C2"][i].get("context") or "").strip()]
    no_ctx = [i for i in ids if i not in set(has_ctx)]
    for name, sub in [("with context/hint", has_ctx), ("no context", no_ctx)]:
        acc = {k: 100 * sum(val(d[k][i]) for i in sub) / len(sub) for k in CFG}
        L.append(f"| {name} | {len(sub)} | " + " | ".join(f"{acc[k]:.1f}" for k in CFG)
                 + f" | {acc['T16'] - acc['T8']:+.1f} | {acc['T16'] - acc['T4']:+.1f} |")

    # ---------------------------------------------------------------- TextVQA
    t = load("textvqa")
    tids = sorted(set.intersection(*[{i for i, r in rows.items() if not r.get("error")} for rows in t.values()]))
    L += ["", "## TextVQA", "", f"{len(tids)} records valid in all five configs.", "",
          "| config | VQA acc | finish != stop | raw has leading/trailing space | raw != normalized (beyond case/space) | empty | mean answer chars |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for k, rows in t.items():
        rs = [rows[i] for i in tids]
        acc = 100 * sum(val(r) for r in rs) / len(rs)
        fin = sum(r.get("finish_reason") != "stop" for r in rs)
        sp = sum(str(r.get("prediction_raw") or "") != str(r.get("prediction_raw") or "").strip() for r in rs)
        diff = sum(re.sub(r"\W", "", str(r.get("prediction_raw") or "").lower()) != re.sub(r"\W", "", str(r.get("prediction_normalized") or "").lower()) for r in rs)
        emp = sum(not str(r.get("prediction_normalized") or "").strip() for r in rs)
        ml = sum(len(str(r.get("prediction_normalized") or "")) for r in rs) / len(rs)
        L.append(f"| {k} | {acc:.2f} | {fin} | {sp} | {diff} | {emp} | {ml:.1f} |")
    L += ["", "| pair | identical normalized answer |", "|---|---:|"]
    for a, b in PAIRS:
        same = sum(str(t[a][i].get("prediction_normalized")) == str(t[b][i].get("prediction_normalized")) for i in tids)
        L.append(f"| {a} vs {b} | {same} ({100 * same / len(tids):.1f}%) |")

    text = "\n".join(L) + "\n"
    print(text)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text)


if __name__ == "__main__":
    main()
