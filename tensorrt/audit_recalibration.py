#!/usr/bin/env python3
"""TensorRT audit, part 4: does in-domain multimodal calibration close the T8 / T4 gap?

Compares the recalibrated engines (T8m, T4m; tensorrt/quantize_mmcalib.py) with the original text-calibrated
ones (T8, T4), the unquantized TensorRT engine (T16) and the matched llama.cpp configs (C2 Q8_0, C3 Q4_K_M),
record by record. Same statistics as Table B (make_table_b.py): paired percentile bootstrap, 10,000
resamples, seed 249, exact McNemar for binary scores. Only records valid in every config are used.

Usage: python3 tensorrt/audit_recalibration.py [--datasets scienceqa,textvqa] [--out results/audit/recalibration.md]
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from make_table_b import load_results, paired_delta  # noqa: E402

FILES = {
    "C2": "results/config2_F16v_Q8l__{ds}.jsonl",
    "C3": "results/config3_F16v_Q4l__{ds}.jsonl",
    "T16": "results_trt/configT16_TRT_F16v_F16l__{ds}.jsonl",
    "T8": "results_trt/configT8_TRT_F16v_INT8l__{ds}.jsonl",
    "T8m": "results_trt/configT8m_TRT_F16v_INT8l_mmcal__{ds}.jsonl",
    "T4": "results_trt/configT4_TRT_F16v_INT4l__{ds}.jsonl",
    "T4m": "results_trt/configT4m_TRT_F16v_INT4l_mmcal__{ds}.jsonl",
}
LABEL = {"C2": "C2 llama.cpp Q8_0", "C3": "C3 llama.cpp Q4_K_M", "T16": "T16 TRT FP16",
         "T8": "T8 INT8 SQ, text calib", "T8m": "T8m INT8 SQ, image+prompt calib",
         "T4": "T4 INT4 AWQ, text calib", "T4m": "T4m INT4 AWQ, image+prompt calib"}
PAIRS = [("T8", "T8m", "recalibration, INT8"), ("T16", "T8", "INT8 vs FP16, text calib"),
         ("T16", "T8m", "INT8 vs FP16, image+prompt calib"), ("C2", "T8m", "8-bit across runtimes, recalibrated"),
         ("T4", "T4m", "recalibration, INT4"), ("T16", "T4", "INT4 vs FP16, text calib"),
         ("T16", "T4m", "INT4 vs FP16, image+prompt calib"), ("C3", "T4m", "4-bit across runtimes, recalibrated")]


def subset(d, ids):
    return {"valid": {i: v for i, v in d["valid"].items() if i in ids}}


def fmt(r):
    s = f"{r['delta']:+.2f} [{r['ci'][0]:+.2f}, {r['ci'][1]:+.2f}]"
    s = f"**{s}**" if r["ci"][0] > 0 or r["ci"][1] < 0 else s
    if "p_mcnemar" in r:
        s += f" ({r['worse']}/{r['better']}, p={r['p_mcnemar']:.2g})"
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--datasets", default="scienceqa,textvqa")
    ap.add_argument("--out", default=str(ROOT / "results/audit/recalibration.md"))
    ap.add_argument("--n-boot", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=249)
    args = ap.parse_args()

    L = ["# TensorRT audit, part 4: in-domain multimodal recalibration", "",
         "Generated by `tensorrt/audit_recalibration.py`. T8m / T4m = the T8 / T4 quantization (same ModelOpt "
         "config, same exported layers) calibrated on 128 image + prompt pairs from ScienceQA train and TextVQA train "
         "in this project's prompt format, instead of 512 text-only CNN/DailyMail articles. Paired 95% bootstrap CI "
         "(10,000 resamples, seed 249); bold = interval excludes 0; for binary scores (worse/better, McNemar p).", ""]
    for di, ds in enumerate([d.strip() for d in args.datasets.split(",") if d.strip()]):
        paths = {k: ROOT / v.format(ds=ds) for k, v in FILES.items()}
        missing = [k for k, p in paths.items() if not p.exists()]
        if missing:
            L += [f"## {ds}", "", f"Not run yet for: {', '.join(missing)}.", ""]
            continue
        data = {k: load_results(p) for k, p in paths.items()}
        ids = set.intersection(*[set(d["valid"]) for d in data.values()])
        L += [f"## {ds} ({len(ids)} records valid in all configs)", "", "| config | accuracy |", "|---|---:|"]
        for k in FILES:
            v = [data[k]["valid"][i] for i in ids]
            L.append(f"| {LABEL[k]} | {100 * sum(v) / len(v):.2f} |")
        L += ["", "| comparison | what it tests | change, points |", "|---|---|---|"]
        for pi, (a, b, what) in enumerate(PAIRS):
            r = paired_delta(subset(data[a], ids), subset(data[b], ids), args.n_boot,
                             np.random.default_rng([args.seed, di, pi]))
            L.append(f"| {a} -> {b} | {what} | {fmt(r)} |")
        gap8 = np.mean([data["T16"]["valid"][i] - data["T8"]["valid"][i] for i in ids])
        gap8m = np.mean([data["T16"]["valid"][i] - data["T8m"]["valid"][i] for i in ids])
        gap4 = np.mean([data["T16"]["valid"][i] - data["T4"]["valid"][i] for i in ids])
        gap4m = np.mean([data["T16"]["valid"][i] - data["T4m"]["valid"][i] for i in ids])
        L += ["", f"Share of the gap to T16 closed by recalibration: INT8 "
              f"{100 * (gap8 - gap8m) / gap8:.0f}% ({100 * gap8:.2f} -> {100 * gap8m:.2f} points), INT4 "
              f"{100 * (gap4 - gap4m) / gap4:.0f}% ({100 * gap4:.2f} -> {100 * gap4m:.2f} points).", ""]
        if ds == "scienceqa":
            ctx = {}
            for line in open(paths["C2"]):
                r = json.loads(line)
                ctx[r["idx"]] = bool((r.get("context") or "").strip())
            L += ["By question type (accuracy, %):", "", "| subset | n | T16 | T8 | T8m | T4 | T4m | C2 | C3 |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for name, sel in [("with text context / hint", True), ("no text context (image only)", False)]:
                sub = [i for i in ids if ctx.get(i) == sel]
                acc = {k: 100 * np.mean([data[k]["valid"][i] for i in sub]) for k in FILES}
                L.append(f"| {name} | {len(sub)} | " + " | ".join(f"{acc[k]:.1f}" for k in
                         ["T16", "T8", "T8m", "T4", "T4m", "C2", "C3"]) + " |")
            L.append("")
    text = "\n".join(L) + "\n"
    print(text)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text)


if __name__ == "__main__":
    main()
