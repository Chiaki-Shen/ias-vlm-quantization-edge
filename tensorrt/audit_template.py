#!/usr/bin/env python3
"""TensorRT audit, part 3: chat template and tokenizer, Edge-LLM vs the model's own template vs llama.cpp.

Checks (x86 host, Edge-LLM venv; needs the exported ONNX dirs and the original HF model):
  1. Edge-LLM renders prompts from processed_chat_template.json. Its render equals the model's own HF
     chat template (AutoProcessor.apply_chat_template) for an image + text user turn.
  2. processed_chat_template.json is the same for T16, T8 and T4 (apart from its model_path field).
  3. tokenizer.json differs between T16 (exported from the original model) and T8/T4 (re-saved by the
     quantizer); every templated benchmark prompt tokenizes to the same ids with both files.
  4. Text tokens per record equal what llama.cpp prefilled besides the image (llama-server log counts,
     results_latency/breakdown, 50 ScienceQA + 50 TextVQA records).

Usage: python tensorrt/audit_template.py --workspace ~/edgellm-workspace [--out results/audit/template.md]
"""
import argparse
import collections
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import run_experiment as rx  # noqa: E402

RESULTS = {"scienceqa": "results/config2_F16v_Q8l__scienceqa.jsonl", "textvqa": "results/config2_F16v_Q8l__textvqa.jsonl",
           "cv_bench": "results/config2_F16v_Q8l__cv_bench.jsonl", "blink_depth": "results/config2_F16v_Q8l__blink_depth.jsonl",
           "blink_spatial": "results/config2_F16v_Q8l__blink_spatial.jsonl"}


def prompt_for(ds, rec):
    spec = rx.DATASET_SPECS[ds]
    return rx.FORMATS[spec["format"]]["prompts"][spec["prompt"]](rec)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--workspace", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=ROOT / "results/audit/template.md")
    args = ap.parse_args()
    ws = args.workspace
    from tokenizers import Tokenizer
    from transformers import AutoProcessor

    L = ["# TensorRT audit, part 3: chat template and tokenizer", "",
         "Generated by `tensorrt/audit_template.py`.", ""]
    tmpl = {c: json.loads((ws / f"{c}/onnx/llm/processed_chat_template.json").read_text())
            for c in ("cr2b-fp16", "cr2b-int8sq", "cr2b-int4awq")}
    strip = lambda d: {k: v for k, v in d.items() if k != "model_path"}  # noqa: E731
    same_tmpl = strip(tmpl["cr2b-fp16"]) == strip(tmpl["cr2b-int8sq"]) == strip(tmpl["cr2b-int4awq"])
    t = tmpl["cr2b-int8sq"]

    def edge_render(prompt):
        u = t["roles"]["user"]
        return u["prefix"] + t["content_types"]["image"]["format"] + prompt + u["suffix"] + t["generation_prompt"]

    proc = AutoProcessor.from_pretrained(ws / "models/Cosmos-Reason2-2B")
    msgs = [{"role": "user", "content": [{"type": "image", "image": "x.jpg"}, {"type": "text", "text": "PROMPT"}]}]
    hf = proc.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
    L += ["## 1-2. Template", "",
          f"- Edge-LLM render: `{edge_render('PROMPT')!r}`",
          f"- HF chat template render: `{hf!r}`",
          f"- identical: **{hf == edge_render('PROMPT')}**; no default system prompt "
          f"(`default_system_prompt` = {t.get('default_system_prompt')!r}); image placed before the text, as in llama.cpp's request",
          f"- processed_chat_template.json identical for T16 / T8 / T4 (ignoring `model_path`): **{same_tmpl}**", ""]

    ta = Tokenizer.from_file(str(ws / "cr2b-fp16/onnx/llm/tokenizer.json"))
    tb = Tokenizer.from_file(str(ws / "cr2b-int8sq/onnx/llm/tokenizer.json"))
    ja = json.loads((ws / "cr2b-fp16/onnx/llm/tokenizer.json").read_text())
    jb = json.loads((ws / "cr2b-int8sq/onnx/llm/tokenizer.json").read_text())
    norm = lambda ms: [m if isinstance(m, str) else " ".join(m) for m in ms]  # noqa: E731
    n = mism = 0
    for ds, f in RESULTS.items():
        for line in open(ROOT / f):
            r = json.loads(line)
            text = edge_render(prompt_for(ds, r))
            n += 1
            mism += ta.encode(text, add_special_tokens=False).ids != tb.encode(text, add_special_tokens=False).ids
    L += ["## 3. Tokenizer files (T16 vs T8/T4)", "",
          f"- vocab identical: **{ja['model']['vocab'] == jb['model']['vocab']}**; added/special tokens identical: "
          f"**{ja['added_tokens'] == jb['added_tokens']}**; merges identical after normalizing the list format: "
          f"**{norm(ja['model']['merges']) == norm(jb['model']['merges'])}**",
          "- differences: merges stored as `\"a b\"` strings vs `[\"a\", \"b\"]` pairs, and ByteLevel `trim_offsets` / "
          "decoder flags (offsets and decoding only). The Edge-LLM C++ tokenizer ranks Qwen merges by vocab, not by the merges list.",
          f"- **{n - mism} of {n}** templated benchmark prompts (all five datasets) tokenize to identical ids with both files", ""]

    rows = list(csv.DictReader(open(ROOT / "results_latency/breakdown/breakdown_requests.csv")))
    recs = {ds: {json.loads(l)["rec_no"]: json.loads(l) for l in open(ROOT / RESULTS[ds])} for ds in ("scienceqa", "textvqa")}
    seen, diffs = set(), collections.defaultdict(collections.Counter)
    for r in rows:
        key = (r["dataset"], r["pos"])
        if r["config"] != "2" or key in seen:
            continue
        seen.add(key)
        text = edge_render(prompt_for(r["dataset"], recs[r["dataset"]][int(r["pos"])]))
        n_edge = len(tb.encode(text, add_special_tokens=False).ids) - 1   # the single <|image_pad|> expands to the image
        diffs[r["dataset"]][int(r["text_tokens"]) - n_edge] += 1
    L += ["## 4. Text tokens vs what llama.cpp prefilled", "",
          "llama.cpp text tokens = llama-server's log count of non-image tokens (Config 2, `results_latency/breakdown`). "
          "Edge-LLM text tokens = templated prompt tokens minus the one `<|image_pad|>` placeholder.", "",
          "| dataset | records | llama.cpp - Edge-LLM text tokens |", "|---|---:|---|"]
    for ds, c in diffs.items():
        L.append(f"| {ds} | {sum(c.values())} | {dict(c)} |")
    text = "\n".join(L) + "\n"
    print(text)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)


if __name__ == "__main__":
    main()
