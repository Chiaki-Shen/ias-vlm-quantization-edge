#!/usr/bin/env python3
"""Error analysis: which records flip between F16 vision (Config 2) and the quantized vision encoders.

TextVQA: every record whose VQA score changes between Config 2 and a quantized-vision config
(5 Q8_0, 9 Q6_K, 10 Q5_K_M, 8 Q4_0, 11 Q3_K_M; language Q8_0 in all) is labelled by how the
quantized answer differs from the F16 answer (normalized predictions, `prediction_normalized` or `predicted`):
  number     both answers are numbers, or differ only in digits (e.g. `12` -> `10`, `1565-1898` -> `1565-1808`)
  misread    character-level near miss: difflib similarity >= 0.6 and neither answer contains the other
             (e.g. `aldo` -> `aldi`, `medstar emergency` -> `medtech emergency`)
  extent     one answer contains the other: a word added or dropped (`winter` -> `winter collection`)
  different  anything else: a different answer
"Lost" = score went down, "gained" = score went up. Config 5 (Q8_0 vision) is close to F16 everywhere in
Table B, so its flips are the run-to-run noise floor: a category matters only if a low-bit config
loses clearly more records there than Config 5 does. Net = lost - gained.

Also: overlap of the records lost by Q4_0 and Q3_K_M, flip rate by answer length (F16 answer, in
characters), and for CV-Bench Count, whether the wrong counts that appear are over- or under-counts.

Usage: python3 scripts/error_analysis.py [--out-dir results/analysis]
Writes error_analysis.md and textvqa_flips.csv (one row per flipped record and config).
"""
import argparse
import csv
import difflib
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

CONFIGS = [(5, "Q8_0"), (9, "Q6_K"), (10, "Q5_K_M"), (8, "Q4_0"), (11, "Q3_K_M")]
CATS = ["number", "misread", "extent", "different"]
SHORT = {2: "F16v_Q8l", 5: "Q8v_Q8l", 9: "Q6v_Q8l", 10: "Q5v_Q8l", 8: "Q4v_Q8l", 11: "Q3v_Q8l"}


def load(cfg, ds):
    rows = {}
    for line in open(f"results/config{cfg}_{SHORT[cfg]}__{ds}.jsonl"):
        if line.strip():
            r = json.loads(line)
            if not r.get("error"):
                rows[r["idx"]] = r
    return rows


def norm(r):
    p = r.get("prediction_normalized")
    return (p if p is not None else str(r.get("predicted") or "")).strip().lower()


def category(a, b):
    if re.sub(r"\d", "#", a) == re.sub(r"\d", "#", b) or (re.fullmatch(r"[\d.,]+", a) and re.fullmatch(r"[\d.,]+", b)):
        return "number"
    if a and b and (a in b or b in a):
        return "extent"
    if difflib.SequenceMatcher(None, a, b).ratio() >= 0.6:
        return "misread"
    return "different"


def length_bucket(s):
    n = len(s)
    return "1-3" if n <= 3 else "4-8" if n <= 8 else "9-15" if n <= 15 else "16+"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default="results/analysis")
    args = ap.parse_args()
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    base = load(2, "textvqa")
    flips, lost_ids, summary = [], {}, {}
    buckets = Counter(length_bucket(norm(r)) for r in base.values())
    lost_by_len = {}
    for cfg, name in CONFIGS:
        other = load(cfg, "textvqa")
        lost, gained = Counter(), Counter()
        lost_ids[cfg] = set()
        lost_by_len[cfg] = Counter()
        common = [i for i in base if i in other]
        for i in common:
            sa, sb = float(base[i]["score"]), float(other[i]["score"])
            if sa == sb:
                continue
            a, b = norm(base[i]), norm(other[i])
            cat = category(a, b) if a != b else "different"
            (lost if sb < sa else gained)[cat] += 1
            if sb < sa:
                lost_ids[cfg].add(i)
                lost_by_len[cfg][length_bucket(a)] += 1
            flips.append({"config": cfg, "vision": name, "idx": i, "direction": "lost" if sb < sa else "gained",
                          "category": cat, "f16_answer": a, "quant_answer": b, "f16_score": sa, "quant_score": sb,
                          "question": base[i]["question"]})
        summary[cfg] = (lost, gained, len(common),
                        100 * sum(float(other[i]["score"]) - float(base[i]["score"]) for i in common) / len(common))

    with open(out / "textvqa_flips.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(flips[0]))
        w.writeheader()
        w.writerows(flips)

    L = ["# Error analysis: records that flip between F16 vision and quantized vision", "",
         "Generated by `scripts/error_analysis.py`. Language decoder Q8_0 in every config; baseline Config 2 "
         "(F16 vision). Per-record flips: `results/analysis/textvqa_flips.csv`.", "",
         "## TextVQA: how the answer changes", "",
         "Records whose VQA score changes vs F16, by how the quantized answer differs from the F16 answer "
         "(categories in the script docstring). Each cell: lost / gained (net = lost - gained). "
         "Config 5 (Q8_0) is the noise floor.", "",
         "| vision | records changed | " + " | ".join(CATS) + " | total | change vs F16 (points) |",
         "|---|---:|" + "---|" * len(CATS) + "---|---:|"]
    for cfg, name in CONFIGS:
        lost, gained, n, d = summary[cfg]
        cells = [f"{lost[c]} / {gained[c]} ({lost[c] - gained[c]:+d})" for c in CATS]
        tl, tg = sum(lost.values()), sum(gained.values())
        L.append(f"| C{cfg} {name} | {tl + tg} | " + " | ".join(cells) + f" | {tl} / {tg} ({tl - tg:+d}) | {d:+.2f} |")
    nf = summary[5]
    L += ["", "Net losses above the Q8_0 noise floor (net minus Config 5's net):", "",
          "| vision | " + " | ".join(CATS) + " | total |", "|---|" + "---:|" * (len(CATS) + 1)]
    for cfg, name in CONFIGS[1:]:
        lost, gained, _, _ = summary[cfg]
        ex = [(lost[c] - gained[c]) - (nf[0][c] - nf[1][c]) for c in CATS]
        L.append(f"| C{cfg} {name} | " + " | ".join(f"{e:+d}" for e in ex) + f" | {sum(ex):+d} |")

    a, b = lost_ids[8], lost_ids[11]
    L += ["", "## TextVQA: do Q4_0 and Q3_K_M lose the same records?", "",
          f"Q4_0 loses {len(a)} records, Q3_K_M {len(b)}; {len(a & b)} are lost by both "
          f"(Jaccard {len(a & b) / len(a | b):.2f}). For scale, Q8_0 loses {len(lost_ids[5])}, "
          f"of which {len(lost_ids[5] & b)} are also lost by Q3_K_M.", "",
          "## TextVQA: share of records lost, by F16 answer length", "",
          "| F16 answer length (chars) | records | " + " | ".join(f"C{c} {n}" for c, n in CONFIGS) + " |",
          "|---|---:|" + "---:|" * len(CONFIGS)]
    for bk in ["1-3", "4-8", "9-15", "16+"]:
        L.append(f"| {bk} | {buckets[bk]} | " + " | ".join(
            f"{100 * lost_by_len[c][bk] / buckets[bk]:.1f}%" for c, _ in CONFIGS) + " |")

    # CV-Bench Count: direction of the count errors that are new vs F16.
    cb = load(2, "cv_bench")
    L += ["", "## CV-Bench Count: over- or under-counting", "",
          "Count records F16 gets right and the quantized config gets wrong (lost), by the sign of "
          "(predicted count - true count). Reverse flips (F16 wrong, quantized right) are counted the same way from F16's answer.", "",
          "| vision | lost | over | under | off by 1 | gained | F16 over / under on those |",
          "|---|---:|---:|---:|---:|---:|---|"]
    for cfg, name in CONFIGS:
        o = load(cfg, "cv_bench")
        lost = Counter()
        gain = Counter()
        for i, r in cb.items():
            if r["task"] != "Count" or i not in o:
                continue
            ch = r["choices"]
            val = lambda letter: float(ch[ord(letter) - 65]) if letter and 0 <= ord(letter) - 65 < len(ch) else None
            gt = val(r["gt_answer"])
            if r["correct"] and not o[i]["correct"]:
                p = val(o[i]["predicted"])
                if p is None or gt is None:
                    lost["unparsed"] += 1
                    continue
                lost["n"] += 1
                lost["over" if p > gt else "under"] += 1
                lost["off1"] += abs(p - gt) == 1
            elif not r["correct"] and o[i]["correct"]:
                p = val(r["predicted"])
                gain["n"] += 1
                if p is not None and gt is not None:
                    gain["over" if p > gt else "under"] += 1
        L.append(f"| C{cfg} {name} | {lost['n']} | {lost['over']} | {lost['under']} | {lost['off1']} | "
                 f"{gain['n']} | {gain['over']} / {gain['under']} |")
    text = "\n".join(L) + "\n"
    (out / "error_analysis.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
