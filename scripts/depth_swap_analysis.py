#!/usr/bin/env python3
"""Depth follow-up: does Q4_K_M language's depth gain survive reversing the answer order?

Inputs: the original runs in results/ (BLINK depth, CV-Bench Depth records) and the swapped runs in
results_depth_swap/ (scripts/prep_swap.py: same records, two choices reversed, ground truth flipped).

Per config (C2 Q8_0 language, C3 Q4_K_M language) and dataset:
  acc original / acc swapped     accuracy in each order
  balanced acc                   mean of the two: the score with answer position balanced out
  "A" share                      share of predictions that are the first option, per order
  consistent                     records where the model picks the same underlying choice in both orders
Then C3 - C2 in the original order, the swapped order and balanced, with paired 95% bootstrap CIs
(10,000 resamples, default_rng([seed, dataset number, order number]), seed 249).

If the gain is real depth perception it stays in both orders; if it comes from a different preference
for answer position, it shrinks or flips in the swapped order and in the balanced score.

Usage: python3 scripts/depth_swap_analysis.py [--out results/analysis/depth_swap.md]
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_table_b import mcnemar_exact, paired_bootstrap  # noqa: E402

CFG = {"C2": "config2_F16v_Q8l", "C3": "config3_F16v_Q4l"}
DATASETS = [("blink_depth", "BLINK depth"), ("cv_bench", "CV-Bench Depth")]


def load(path, keep=lambda r: True):
    rows = {}
    for line in open(path):
        if line.strip():
            r = json.loads(line)
            if not r.get("error") and keep(r):
                rows[r["idx"]] = r
    return rows


def flip(letter):
    return {"A": "B", "B": "A"}.get(letter)


def ci(diff, rng, n_boot):
    if np.allclose(diff, 0):
        return 0.0, 0.0
    lo, hi = paired_bootstrap(diff, n_boot, rng)
    return lo * 100, hi * 100


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--orig", default="results")
    ap.add_argument("--swap", default="results_depth_swap")
    ap.add_argument("--out", default="results/analysis/depth_swap.md")
    ap.add_argument("--n-boot", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=249)
    args = ap.parse_args()

    L = ["# Depth follow-up: answer-order swap", "",
         "Generated by `scripts/depth_swap_analysis.py`. Swapped = same records with the two choices reversed "
         "(`scripts/prep_swap.py`). Balanced = mean of the original and swapped scores.", "",
         "| config | dataset | n | acc original | acc swapped | balanced | \"A\" share orig / swapped | same choice in both orders |",
         "|---|---|---:|---:|---:|---:|---|---:|"]
    deltas = ["", "## C3 (Q4_K_M) - C2 (Q8_0), points, paired 95% bootstrap CI", "",
              "| dataset | original order | swapped order | balanced | McNemar p (orig / swapped) |", "|---|---|---|---|---|"]
    for di, (ds, label) in enumerate(DATASETS):
        keep = (lambda r: r.get("task") == "Depth") if ds == "cv_bench" else (lambda r: True)
        o, s = {}, {}
        for c, stem in CFG.items():
            o[c] = load(Path(args.orig) / f"{stem}__{ds}.jsonl", keep)
            s[c] = load(Path(args.swap) / f"{stem}__{ds}.jsonl")
        ids = sorted(set.intersection(*[set(o[c]) & set(s[c]) for c in CFG]))
        sc = {}
        for c in CFG:
            a = np.array([float(bool(o[c][i]["correct"])) for i in ids])
            b = np.array([float(bool(s[c][i]["correct"])) for i in ids])
            sc[c] = (a, b)
            share_o = 100 * np.mean([o[c][i]["predicted"] == "A" for i in ids])
            share_s = 100 * np.mean([s[c][i]["predicted"] == "A" for i in ids])
            same = 100 * np.mean([flip(s[c][i]["predicted"]) == o[c][i]["predicted"] for i in ids])
            L.append(f"| {c} | {label} | {len(ids)} | {100 * a.mean():.2f} | {100 * b.mean():.2f} | "
                     f"{50 * (a.mean() + b.mean()):.2f} | {share_o:.1f} / {share_s:.1f} | {same:.1f}% |")
        cells = []
        for oi, (x, y) in enumerate([(sc["C2"][0], sc["C3"][0]), (sc["C2"][1], sc["C3"][1]),
                                     ((sc["C2"][0] + sc["C2"][1]) / 2, (sc["C3"][0] + sc["C3"][1]) / 2)]):
            d = y - x
            lo, hi = ci(d, np.random.default_rng([args.seed, di, oi]), args.n_boot)
            txt = f"{100 * d.mean():+.2f} [{lo:+.2f}, {hi:+.2f}]"
            cells.append(f"**{txt}**" if lo > 0 or hi < 0 else txt)
        ps = []
        for x, y in [(sc["C2"][0], sc["C3"][0]), (sc["C2"][1], sc["C3"][1])]:
            ps.append(f"{mcnemar_exact(int(((x == 1) & (y == 0)).sum()), int(((x == 0) & (y == 1)).sum())):.3g}")
        deltas.append(f"| {label} | " + " | ".join(cells) + f" | {ps[0]} / {ps[1]} |")
    text = "\n".join(L + deltas) + "\n"
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
